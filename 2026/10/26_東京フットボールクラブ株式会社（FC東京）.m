# 本文
日頃よりFC東京にご支援・ご声援をいただき、誠にありがとうございます。

当クラブ公式ホームページの一部ページにおいて、使用していたプログラムを第三者に悪用され、当サイトのURLのまま当クラブと無関係の内容が表示される、またはアクセスした方が外部サイトへ自動的に転送される事象が確認されました。

表示・転送された内容は、詐欺サイト等である可能性があります。本件により、みなさまにご心配とご迷惑をおかけしておりますことを、深くお詫び申し上げます。

## 発生期間

2026年9月13日(日)19:53頃 ～ 2026年10月26日(月)11:00頃

## 対象ページ

『味の素スタジアム席割図』(スタジアム座席の360°パノラマビュー)ページ

（対象ページ：/panorama/ 配下）

※英語版などの翻訳ページを含む

## 発生していた事象

- 検索エンジンの検索結果等に、当サイトのURL(fctokyo.co.jp)で始まる不審なリンクが表示される

- 当該リンクを開くと、当サイトのURLのまま当クラブと無関係の内容が表示される、または当クラブと無関係の外部サイトへ自動的に転送される

## 個人情報への影響について

本事象は、第三者が細工したリンクを通じて閲覧者を外部サイトへ誘導するもので、当サイトのサーバーへの侵入を伴うものではございません。

また、現時点では当クラブが保有するお客様の個人情報の流出は確認されておりません。

## 当クラブの対応

2026年10月26日(月)10:00頃に本事象を認識し、調査および対応を開始しました。

同日11:00頃に、不正な表示・転送を防止する措置を講じました。

また、当該パノラマビューページの公開を終了し、本事象に関連する不審なリンクについても、可能な限り削除の対応を実施しています。不審な検索結果やリンクが表示された場合は、アクセスしないようお願いいたします。

## みなさまへのお願い

本事象への対策は完了しておりますが、以下にご注意ください。

#### ①不審なリンクへのアクセスについて

当サイトのURLであっても、検索結果やSNS等で、通常と異なるタイトルや不審な内容・文字列が表示されているリンクにはアクセスしないようにお願いいたします。

#### ②不審なサイトで情報を入力された場合の対応について

万一、本事象により表示・転送された当クラブとは無関係の不審なサイトで情報を入力された場合は、以下のとおりご対応をお願いいたします。

- クレジットカード情報を入力された場合は、速やかにカード会社へご連絡ください。

- ID・パスワードを入力された場合は、同じものをご利用の他のサービスも含め、パスワードを変更してください。

- 氏名や電話番号等の個人情報を入力された場合は、不審なメールやSMS、電話等にご注意ください。

#### ③当クラブからのお知らせの確認について

- 当クラブからのお知らせは、公式サイトトップページおよび公式Xアカウントからご確認ください。

みなさまにはご心配とご迷惑をおかけしましたことを、重ねて深くお詫び申し上げます。

